"""Build supplementary tables directly from the recorded row-level analyses."""
import ast
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent / 'supplementary_tables.tex'


def rows(path):
    with path.open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def title(method):
    return 'SD-TokenSkip' if method == 'sd_frozen' else '$\\gamma=' + method[-3:] + '$'


def main():
    lengths = rows(ROOT / 'experiments/matched-length-analysis/lengths.csv')
    paired = rows(ROOT / 'experiments/matched-20261107/analysis/paired_comparisons.csv')
    groups = rows(ROOT / 'experiments/matched-20261107/analysis/group_comparisons.csv')
    parts = ['% Generated by build_supplementary_tables.py.']
    for size in ('3b', '7b'):
        model = 'qwen2.5-' + size
        parts += [r'\subsection{Token counts and stopping: Qwen2.5-'+size.upper()+r'}',
            r'\begin{table}[H]\centering\small',
            r'\caption{Output lengths and termination for '+size.upper()+r'. Each condition has 1,319 questions.}',
            r'\begin{tabular}{lrrrr}', r'\toprule',
            r'Condition & CoT & Generated & Length stop & Separator\\', r'\midrule']
        for row in lengths:
            if row['model'] == model:
                parts.append(f"{title(row['condition'])} & {float(row['mean_cot_tokens']):.2f} & {float(row['mean_generated_tokens']):.2f} & {row['length_finish_count']} & {row['separator_count']}" + r'\\')
        parts += [r'\bottomrule\end{tabular}\end{table}',
            'CoT and generated are means per question; the two rightmost columns are counts. '
            'The generated count excludes EOS. The separator column counts the exact marker used '
            'to split the completion. A length stop and a missing marker are distinct events.']
        parts += [r'\subsection{Paired fixed-ratio comparisons: Qwen2.5-'+size.upper()+r'}',
            r'\begin{table}[H]\centering\small',
            r'\caption{SD minus each fixed condition for '+size.upper()+r'. Token reduction uses the fixed condition as denominator.}',
            r'\begin{tabular}{lrrr}', r'\toprule',
            r'Fixed $\gamma$ & $\Delta$ accuracy [95\% CI] & Token reduction (\%) & McNemar $p$\\',r'\midrule']
        for gamma in ('1.0','0.9','0.8','0.7','0.6','0.5'):
            row = next(r for r in paired if r['model'] == model and r['a'] == 'sd_frozen' and r['b'] == 'fixed_'+gamma)
            lo, hi = ast.literal_eval(row['delta_accuracy_ci95'])
            parts.append(f"{gamma} & {float(row['delta_accuracy_pp']):+.2f} [{lo:+.2f}, {hi:+.2f}] & {float(row['cot_reduction_percent']):+.2f} & {float(row['mcnemar_exact_two_sided_p']):.3g}" + r'\\')
        parts += [r'\bottomrule\end{tabular}\end{table}',
            'Accuracy intervals are paired bootstrap intervals in percentage points. Positive token '
            'reduction means SD used fewer tokens; a negative value means SD used more. The $p$-values '
            'in this table are unadjusted and should not be treated as confirmatory tests across all ratios.']
        parts += [r'\subsection{Risk groups: Qwen2.5-'+size.upper()+r'}',
            r'\begin{table}[H]\centering\small',
            r'\caption{Test outcomes by structural-score group for '+size.upper()+r'. Fixed settings use the same questions within each group.}',
            r'\begin{tabular}{llrrr}',r'\toprule',
            r'Group & Condition & Correct / $N$ & Mean CoT & Lost vs $1.0$\\',r'\midrule']
        for group in ('easy','medium','hard'):
            for method in ('fixed_1.0','fixed_0.5','sd_frozen'):
                row = next(r for r in groups if r['model']==model and r['group']==group and r['method']==method)
                parts.append(f"{group.title()} & {title(method)} & {row['correct']}/{row['n']} & {float(row['mean_cot_tokens']):.2f} & {row['lost_vs_gamma1']}" + r'\\')
        parts += [r'\bottomrule\end{tabular}\end{table}',
            'Lost counts questions correct at fixed 1.0 but incorrect in the listed condition; '
            'they exclude recovered answers. These labels are structural score bands, not human '
            'difficulty annotations. The SD condition may choose different ratios within a band '
            'because of fallback. The analysis is exploratory on the previously inspected test set.']
    OUT.write_text('\n\n'.join(parts)+'\n', encoding='utf-8')
    print('Wrote', OUT)


if __name__ == '__main__':
    main()
