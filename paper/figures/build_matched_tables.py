"""Render the paper's direct-inference table from the verified run metrics."""
import json
from pathlib import Path

FIGURES = Path(__file__).resolve().parent
EXPERIMENT = FIGURES.parents[1] / "experiments/matched-20261107"
ANALYSIS = EXPERIMENT / "analysis/analysis.json"


def main():
    results = json.loads(ANALYSIS.read_text(encoding="utf-8"))["models"]
    models = ("qwen2.5-3b", "qwen2.5-7b")
    methods = [f"fixed_{gamma / 10:.1f}" for gamma in range(5, 11)] + ["sd_frozen"]
    lines = ["% Generated by build_matched_tables.py from the matched run analysis."]
    for method in methods:
        label = r"SD-TokenSkip" if method == "sd_frozen" else "$\\gamma=" + method[6:] + "$"
        cells = [label]
        for model in models:
            assert results[model]["status"] == "complete"
            metric = results[model]["metrics"][method]
            assert metric["n"] == 1319
            cells += [f'{metric["correct"]:,}', f'{metric["accuracy_percent"]:.2f}', f'{metric["mean_cot_tokens"]:.2f}']
        if method == "sd_frozen":
            lines.append(r"\midrule")
        lines.append(" & ".join(cells) + r" \\")
    lines.append(r"\bottomrule")
    (FIGURES / "matched_results_rows.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for model in models:
        separate = ["% Generated from matched inference analysis."]
        for method in methods:
            metric = results[model]["metrics"][method]
            assert metric['n'] == 1319
            if method == 'sd_frozen':
                separate.append(r'\midrule')
            label = 'SD-TokenSkip' if method == 'sd_frozen' else '$\\gamma=' + method[6:] + '$'
            reference = results[model]['metrics']['fixed_1.0']['mean_cot_tokens']
            utility = metric['accuracy_percent'] + 10 * (1 - metric['mean_cot_tokens'] / reference)
            separate.append(f"{label} & {metric['correct']:,} & {metric['accuracy_percent']:.2f} & {metric['mean_cot_tokens']:.2f} & {utility:.2f}" + r' \\')
        separate.append(r'\bottomrule')
        (FIGURES / f'matched_{model[-2:]}_rows.tex').write_text('\n'.join(separate) + '\n', encoding='utf-8', newline='\n')


if __name__ == "__main__":
    main()
